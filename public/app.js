let currentLang = localStorage.getItem("weddingLanguage") || "de";
let guestSerial = 0;
let selectedPhotos = [];

function t(key) {
  return translations[currentLang][key] || translations.de[key] || key;
}

function applyLanguage(lang, closeGate) {
  currentLang = lang === "it" ? "it" : "de";
  document.documentElement.lang = currentLang;
  localStorage.setItem("weddingLanguage", currentLang);

  document.querySelectorAll("[data-i18n]").forEach(function (node) {
    var key = node.getAttribute("data-i18n");
    if (translations[currentLang][key] !== undefined) node.textContent = translations[currentLang][key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
    node.placeholder = t(node.getAttribute("data-i18n-placeholder"));
  });

  var switcher = document.getElementById("langSwitch");
  if (switcher) switcher.textContent = currentLang === "de" ? "IT" : "DE";
  syncGuestLabels();

  document.body.classList.remove("lang-pending");
  document.body.classList.add("is-ready");

  if (closeGate) {
    var gate = document.getElementById("languageGate");
    gate.classList.add("is-closing");
    window.setTimeout(function () { gate.hidden = true; }, 760);
  }
}

function syncGuestLabels() {
  document.querySelectorAll(".guest-card").forEach(function (card, index) {
    var heading = card.querySelector(".guest-heading");
    var first = card.querySelector(".guest-label-first");
    var last = card.querySelector(".guest-label-last");
    var diet = card.querySelector(".guest-label-diet");
    var remove = card.querySelector(".guest-remove");
    if (heading) heading.textContent = t("guest") + " " + (index + 1);
    if (first) first.textContent = t("firstName");
    if (last) last.textContent = t("lastName");
    if (diet) diet.textContent = t("dietary");
    if (remove) remove.setAttribute("aria-label", t("removeGuest"));
  });
}

function addGuest(removable) {
  var template = document.getElementById("guestTemplate");
  var fragment = template.content.cloneNode(true);
  var card = fragment.querySelector(".guest-card");
  card.dataset.guestId = String(++guestSerial);
  var remove = card.querySelector(".guest-remove");
  if (!removable) remove.hidden = true;
  remove.addEventListener("click", function () {
    card.remove();
    syncGuestLabels();
  });
  document.getElementById("guestList").appendChild(fragment);
  syncGuestLabels();
}

function setAttendanceState() {
  var attending = document.querySelector('input[name="attending"]:checked').value === "yes";
  var area = document.getElementById("guestArea");
  area.classList.toggle("is-hidden", !attending);
  area.querySelectorAll("input[data-field]").forEach(function (input) {
    input.required = attending && input.dataset.field !== "dietary";
  });
}

function countdown() {
  var target = new Date("2027-07-10T00:00:00+02:00").getTime();
  var now = Date.now();
  var diff = Math.max(0, target - now);
  var days = Math.floor(diff / 86400000);
  var hours = Math.floor((diff % 86400000) / 3600000);
  var minutes = Math.floor((diff % 3600000) / 60000);
  var seconds = Math.floor((diff % 60000) / 1000);
  document.getElementById("countDays").textContent = String(days).padStart(3, "0");
  document.getElementById("countHours").textContent = String(hours).padStart(2, "0");
  document.getElementById("countMinutes").textContent = String(minutes).padStart(2, "0");
  document.getElementById("countSeconds").textContent = String(seconds).padStart(2, "0");
}

function initReveal() {
  var items = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window)) {
    items.forEach(function (item) { item.classList.add("is-visible"); });
    return;
  }
  var observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
  items.forEach(function (item) { observer.observe(item); });
}

function initPetals() {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  var host = document.querySelector(".petals");
  for (var i = 0; i < 12; i += 1) {
    var p = document.createElement("span");
    p.className = "petal";
    p.style.setProperty("--left", (4 + Math.random() * 92) + "%");
    p.style.setProperty("--delay", (-Math.random() * 16) + "s");
    p.style.setProperty("--fall", (12 + Math.random() * 10) + "s");
    p.style.setProperty("--rotate", (Math.random() * 180) + "deg");
    host.appendChild(p);
  }
}

async function submitRsvp(event) {
  event.preventDefault();
  var form = event.currentTarget;
  var status = document.getElementById("rsvpStatus");
  var submit = form.querySelector('button[type="submit"]');

  if (!form.reportValidity()) return;

  var attending = form.elements.attending.value === "yes";
  var guests = [];
  if (attending) {
    document.querySelectorAll(".guest-card").forEach(function (card) {
      guests.push({
        firstName: card.querySelector('[data-field="firstName"]').value.trim(),
        lastName: card.querySelector('[data-field="lastName"]').value.trim(),
        dietary: card.querySelector('[data-field="dietary"]').value.trim()
      });
    });
  }

  var payload = {
    contactName: form.elements.contactName.value.trim(),
    contactEmail: form.elements.contactEmail.value.trim(),
    attending: attending,
    language: currentLang,
    notes: form.elements.notes.value.trim(),
    guests: guests
  };

  submit.disabled = true;
  status.className = "form-status";
  status.textContent = t("rsvpSending");

  try {
    var response = await fetch("/api/rsvp", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });
    var data = await response.json().catch(function () { return {}; });
    if (response.ok) {
      status.className = "form-status success";
      status.textContent = t("rsvpSuccess");
    } else if (response.status === 503) {
      status.className = "form-status error";
      status.textContent = t("rsvpUnavailable");
    } else {
      throw new Error(data.error || "RSVP failed");
    }
  } catch (error) {
    status.className = "form-status error";
    status.textContent = t("rsvpError");
  } finally {
    submit.disabled = false;
  }
}

function formatBytes(bytes) {
  if (bytes < 1024 * 1024) return Math.max(1, Math.round(bytes / 1024)) + " KB";
  return (bytes / (1024 * 1024)).toFixed(1) + " MB";
}

function setSelectedPhotos(files) {
  var allowed = Array.from(files || []).filter(function (file) {
    return file.type.startsWith("image/") || /\.(heic|heif)$/i.test(file.name);
  }).slice(0, 12);
  selectedPhotos = allowed;
  var list = document.getElementById("uploadFiles");
  list.innerHTML = "";
  allowed.forEach(function (file) {
    var row = document.createElement("div");
    row.className = "upload-file";
    var name = document.createElement("span");
    name.textContent = file.name;
    var size = document.createElement("span");
    size.textContent = formatBytes(file.size);
    row.append(name, size);
    list.appendChild(row);
  });
  document.getElementById("uploadSubmit").disabled = allowed.length === 0;
}

async function uploadPhotos() {
  var status = document.getElementById("uploadStatus");
  var button = document.getElementById("uploadSubmit");
  if (!selectedPhotos.length) {
    status.className = "form-status error";
    status.textContent = t("uploadNone");
    return;
  }

  button.disabled = true;
  status.className = "form-status";
  status.textContent = t("uploadUploading");
  var unavailable = false;
  var failed = false;

  for (var i = 0; i < selectedPhotos.length; i += 1) {
    var body = new FormData();
    body.append("photo", selectedPhotos[i]);
    body.append("language", currentLang);
    try {
      var response = await fetch("/api/photos", { method: "POST", body: body });
      if (response.status === 503) unavailable = true;
      else if (!response.ok) failed = true;
    } catch (error) {
      failed = true;
    }
    if (unavailable) break;
  }

  if (unavailable) {
    status.className = "form-status error";
    status.textContent = t("uploadUnavailable");
  } else if (failed) {
    status.className = "form-status error";
    status.textContent = t("uploadError");
  } else {
    status.className = "form-status success";
    status.textContent = t("uploadSuccess");
    selectedPhotos = [];
    document.getElementById("photoInput").value = "";
    document.getElementById("uploadFiles").innerHTML = "";
  }
  button.disabled = selectedPhotos.length === 0;
}

document.addEventListener("DOMContentLoaded", function () {
  var saved = localStorage.getItem("weddingLanguage");
  if (saved === "de" || saved === "it") {
    applyLanguage(saved, true);
  }

  document.querySelectorAll("[data-choose-lang]").forEach(function (button) {
    button.addEventListener("click", function () { applyLanguage(button.dataset.chooseLang, true); });
  });

  document.getElementById("langSwitch").addEventListener("click", function () {
    applyLanguage(currentLang === "de" ? "it" : "de", false);
  });

  document.querySelectorAll("[data-footer-lang]").forEach(function (button) {
    button.addEventListener("click", function () {
      applyLanguage(button.dataset.footerLang, false);
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
  });

  addGuest(false);
  document.getElementById("addGuest").addEventListener("click", function () {
    if (document.querySelectorAll(".guest-card").length < 10) addGuest(true);
  });

  document.querySelectorAll('input[name="attending"]').forEach(function (radio) {
    radio.addEventListener("change", setAttendanceState);
  });
  setAttendanceState();

  document.getElementById("rsvpForm").addEventListener("submit", submitRsvp);

  var photoInput = document.getElementById("photoInput");
  var dropzone = document.getElementById("uploadDropzone");
  dropzone.addEventListener("click", function () { photoInput.click(); });
  photoInput.addEventListener("change", function () { setSelectedPhotos(photoInput.files); });
  ["dragenter", "dragover"].forEach(function (type) {
    dropzone.addEventListener(type, function (event) {
      event.preventDefault();
      dropzone.classList.add("is-dragging");
    });
  });
  ["dragleave", "drop"].forEach(function (type) {
    dropzone.addEventListener(type, function (event) {
      event.preventDefault();
      dropzone.classList.remove("is-dragging");
    });
  });
  dropzone.addEventListener("drop", function (event) { setSelectedPhotos(event.dataTransfer.files); });
  document.getElementById("uploadSubmit").addEventListener("click", uploadPhotos);

  var hero = document.querySelector(".hero");
  hero.addEventListener("pointermove", function (event) {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    var rect = hero.getBoundingClientRect();
    var x = ((event.clientX - rect.left) / rect.width - .5) * 18;
    var y = ((event.clientY - rect.top) / rect.height - .5) * 18;
    hero.style.setProperty("--mx", x + "px");
    hero.style.setProperty("--my", y + "px");
  });

  countdown();
  window.setInterval(countdown, 1000);
  initReveal();
  initPetals();
});
